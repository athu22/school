const formatYearToMarathiWords = (year) => {
  if (year >= 2000 && year < 2100) {
    const remainder = year - 2000;
    if (remainder === 0) return 'दोन हजार';
    return `दोन हजार ${marathiNumbers[remainder]}`;
  } else if (year >= 1900 && year < 2000) {
    const remainder = year - 1900;
    if (remainder === 0) return 'एक हजार नऊशे';
    return `एक हजार नऊशे ${marathiNumbers[remainder]}`;
  } else {
    // Basic fallback for other years
    return year.toString().split('').map(digit => marathiNumbers[parseInt(digit)] || digit).join(' ');
  }
};

export const marathiFormatter = {
  toDateInMarathiWords: (dateStr) => {
    if (!dateStr) return '';
    try {
      const parts = dateStr.split('-');
      if (parts.length !== 3) return dateStr;
      
      const year = parseInt(parts[0], 10);
      const month = parseInt(parts[1], 10);
      const day = parseInt(parts[2], 10);

      const dayWords = marathiNumbers[day] || day.toString();
      const monthWords = marathiMonths[month] || '';
      const yearWords = formatYearToMarathiWords(year);

      return `${dayWords} ${monthWords} ${yearWords}`.trim();
    } catch (e) {
      console.error('Error formatting date in Marathi:', e);
      return dateStr;
    }
  }
};
